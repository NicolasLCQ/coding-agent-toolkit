[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

. (Join-Path $PSScriptRoot 'AgentToolkit.Common.ps1')

$userProfilePath = [Environment]::GetFolderPath([Environment+SpecialFolder]::UserProfile)
if ([string]::IsNullOrWhiteSpace($userProfilePath)) {
    throw 'Unable to determine the current user profile directory.'
}

$toolkitRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$profileRoot = [IO.Path]::GetFullPath($userProfilePath)
$personalAgentRoot = Join-Path $profileRoot '.agents'
$personalSkillPath = Join-Path $personalAgentRoot 'skills'
$sourceSkillPath = Join-Path $toolkitRoot 'skills'

$skillItem = Get-Item -LiteralPath $personalSkillPath -Force -ErrorAction SilentlyContinue
if ($null -eq $skillItem) {
    Write-Host "No personal skill installation found at: $personalSkillPath"
}
elseif (($skillItem.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
    $linkTargets = @($skillItem.Target)
    $pointsToToolkit = $linkTargets | Where-Object {
        -not [string]::IsNullOrWhiteSpace($_) -and
        [IO.Path]::GetFullPath($_) -eq $sourceSkillPath
    }

    if ($pointsToToolkit) {
        [IO.Directory]::Delete($personalSkillPath)
        Write-Host "Removed personal skill link: $personalSkillPath"
    }
    else {
        Write-Warning "Preserved a personal skill link not owned by this toolkit: $personalSkillPath"
    }
}
elseif (-not $skillItem.PSIsContainer) {
    Write-Warning "Preserved a personal skill path that is not a directory: $personalSkillPath"
}
else {
    $manifestPath = Join-Path $personalSkillPath '.agent-toolkit.manifest.json'
    if (-not [IO.File]::Exists($manifestPath)) {
        Write-Warning "Preserved a personal skill directory with no toolkit manifest: $personalSkillPath"
    }
    else {
        try {
            $manifest = [IO.File]::ReadAllText($manifestPath) | ConvertFrom-Json
        }
        catch {
            throw "The toolkit skill manifest is invalid: $manifestPath"
        }

        if ($manifest.generatedBy -ne 'coding-agent-toolkit') {
            Write-Warning "Preserved a personal skill directory with an unrelated manifest: $personalSkillPath"
        }
        else {
            $managedSkillPaths = foreach ($skillName in @($manifest.skills)) {
                if ($skillName -notmatch '^[a-zA-Z0-9][a-zA-Z0-9._-]*$') {
                    throw "The skill manifest contains an unsafe skill name: $skillName"
                }

                $skillPath = Join-Path $personalSkillPath $skillName
                if ([IO.Directory]::Exists($skillPath)) {
                    $managedSkillItem = Get-Item -LiteralPath $skillPath -Force
                    if (($managedSkillItem.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
                        throw "Refusing to remove a managed skill directory that is a filesystem link: $skillPath"
                    }
                }

                $skillPath
            }

            foreach ($managedSkillPath in $managedSkillPaths) {
                Remove-ToolkitManagedDirectory `
                    -Path $managedSkillPath `
                    -ExpectedParentPath $personalSkillPath
            }

            [IO.File]::Delete($manifestPath)
            if ([IO.Directory]::GetFileSystemEntries($personalSkillPath).Count -eq 0) {
                [IO.Directory]::Delete($personalSkillPath)
            }

            Write-Host "Removed copied toolkit skills from: $personalSkillPath"
        }
    }
}

if (
    [IO.Directory]::Exists($personalAgentRoot) -and
    [IO.Directory]::GetFileSystemEntries($personalAgentRoot).Count -eq 0
) {
    [IO.Directory]::Delete($personalAgentRoot)
}

$codexRoot = Join-Path $profileRoot '.codex'
$codexAgentPath = Join-Path $codexRoot 'AGENTS.md'
if (-not [IO.File]::Exists($codexAgentPath)) {
    Write-Host "No global Codex instructions found at: $codexAgentPath"
}
elseif (Test-ToolkitGeneratedFile -Path $codexAgentPath) {
    [IO.File]::Delete($codexAgentPath)
    Write-Host "Removed global Codex instructions: $codexAgentPath"
}
else {
    Write-Warning "Preserved global Codex instructions not generated by this toolkit: $codexAgentPath"
}

if (
    [IO.Directory]::Exists($codexRoot) -and
    [IO.Directory]::GetFileSystemEntries($codexRoot).Count -eq 0
) {
    [IO.Directory]::Delete($codexRoot)
}
