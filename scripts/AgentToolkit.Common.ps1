Set-StrictMode -Version Latest

$script:GeneratedMarker = '<!-- Generated by coding-agent-toolkit. Do not edit directly. -->'
$script:ManagedBlockStart = '<!-- coding-agent-toolkit:start -->'
$script:ManagedBlockEnd = '<!-- coding-agent-toolkit:end -->'

function Test-ToolkitGeneratedFile {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$Path
    )

    $fullPath = [IO.Path]::GetFullPath($Path)
    if (-not [IO.File]::Exists($fullPath)) {
        return $false
    }

    $existingLines = [IO.File]::ReadAllLines($fullPath)
    return $existingLines.Count -gt 0 -and $existingLines[0] -eq $script:GeneratedMarker
}

function Get-ToolkitInstructionDocument {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$InstructionSourcePath,

        [Parameter(Mandatory)]
        [string]$InstallScriptName
    )

    $sourcePath = [IO.Path]::GetFullPath($InstructionSourcePath)
    if (-not [IO.Directory]::Exists($sourcePath)) {
        throw "Instruction source directory does not exist: $sourcePath"
    }

    $files = Get-ChildItem -LiteralPath $sourcePath -File -Filter '*.instructions.md' | Sort-Object Name
    if ($files.Count -eq 0) {
        throw "No *.instructions.md files were found in: $sourcePath"
    }

    $sections = foreach ($file in $files) {
        $content = [IO.File]::ReadAllText($file.FullName)
        $body = [Text.RegularExpressions.Regex]::Replace(
            $content,
            '\A---\r?\n.*?\r?\n---\r?\n',
            '',
            [Text.RegularExpressions.RegexOptions]::Singleline
        ).Trim()

        if ([string]::IsNullOrWhiteSpace($body)) {
            throw "Instruction file has no Markdown body: $($file.FullName)"
        }

        "## Source: $($file.Name)`n`n$body"
    }

    return @(
        '# Shared agent instructions'
        ''
        'These instructions are generated from the files in `instructions/`.'
        "Update those source files and run ``./scripts/$InstallScriptName`` again."
        ''
        ($sections -join "`n`n---`n`n")
        ''
    ) -join "`n"
}

function Set-ToolkitManagedBlock {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$Path,

        [Parameter(Mandatory)]
        [string]$Content
    )

    $fullPath = [IO.Path]::GetFullPath($Path)
    $existingContent = if ([IO.File]::Exists($fullPath)) {
        [IO.File]::ReadAllText($fullPath)
    }
    else {
        ''
    }

    if (Test-ToolkitGeneratedFile -Path $fullPath) {
        $existingContent = ''
    }

    $hasStart = $existingContent.Contains($script:ManagedBlockStart)
    $hasEnd = $existingContent.Contains($script:ManagedBlockEnd)
    if ($hasStart -ne $hasEnd) {
        throw "The managed instruction block is malformed: $fullPath"
    }

    $managedBlock = @(
        $script:ManagedBlockStart
        $Content.Trim()
        $script:ManagedBlockEnd
    ) -join "`n"

    if ($hasStart) {
        $pattern = '(?s)' +
            [Text.RegularExpressions.Regex]::Escape($script:ManagedBlockStart) +
            '.*?' +
            [Text.RegularExpressions.Regex]::Escape($script:ManagedBlockEnd)
        $newContent = [Text.RegularExpressions.Regex]::Replace(
            $existingContent,
            $pattern,
            [Text.RegularExpressions.MatchEvaluator]{ param($match) $managedBlock },
            1
        )
    }
    elseif ([string]::IsNullOrWhiteSpace($existingContent)) {
        $newContent = $managedBlock
    }
    else {
        $newContent = $existingContent.TrimEnd() + "`n`n" + $managedBlock
    }

    $parentPath = [IO.Path]::GetDirectoryName($fullPath)
    [IO.Directory]::CreateDirectory($parentPath) | Out-Null
    [IO.File]::WriteAllText(
        $fullPath,
        $newContent.TrimEnd() + [Environment]::NewLine,
        [Text.UTF8Encoding]::new($false)
    )
}

function Remove-ToolkitManagedBlock {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$Path
    )

    $fullPath = [IO.Path]::GetFullPath($Path)
    if (-not [IO.File]::Exists($fullPath)) {
        return $false
    }
    if (Test-ToolkitGeneratedFile -Path $fullPath) {
        [IO.File]::Delete($fullPath)
        return $true
    }

    $content = [IO.File]::ReadAllText($fullPath)
    $hasStart = $content.Contains($script:ManagedBlockStart)
    $hasEnd = $content.Contains($script:ManagedBlockEnd)
    if (-not $hasStart -and -not $hasEnd) {
        return $false
    }
    if ($hasStart -ne $hasEnd) {
        throw "The managed instruction block is malformed: $fullPath"
    }

    $pattern = '(?s)\s*' +
        [Text.RegularExpressions.Regex]::Escape($script:ManagedBlockStart) +
        '.*?' +
        [Text.RegularExpressions.Regex]::Escape($script:ManagedBlockEnd) +
        '\s*'
    $newContent = [Text.RegularExpressions.Regex]::Replace($content, $pattern, '', 1).Trim()
    if ([string]::IsNullOrWhiteSpace($newContent)) {
        [IO.File]::Delete($fullPath)
    }
    else {
        [IO.File]::WriteAllText(
            $fullPath,
            $newContent + [Environment]::NewLine,
            [Text.UTF8Encoding]::new($false)
        )
    }

    return $true
}

function Install-ToolkitSkills {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$SkillSourcePath,

        [Parameter(Mandatory)]
        [string]$DestinationPath,

        [ValidateSet('Link', 'Copy')]
        [string]$InstallMode = 'Link',

        [switch]$Force
    )

    $sourcePath = [IO.Path]::GetFullPath($SkillSourcePath)
    $destinationPath = [IO.Path]::GetFullPath($DestinationPath)
    if (-not [IO.Directory]::Exists($sourcePath)) {
        throw "Skill source directory does not exist: $sourcePath"
    }

    $destinationItem = Get-Item -LiteralPath $destinationPath -Force -ErrorAction SilentlyContinue
    if ($null -ne $destinationItem -and ($destinationItem.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
        $pointsToLegacyToolkit = @($destinationItem.Target) | Where-Object {
            -not [string]::IsNullOrWhiteSpace($_) -and
            [IO.Path]::GetFullPath($_) -eq $sourcePath
        }
        if (-not $pointsToLegacyToolkit) {
            throw "The personal skill root is a filesystem link not owned by this toolkit: $destinationPath"
        }

        [IO.Directory]::Delete($destinationPath)
    }
    elseif ($null -ne $destinationItem -and -not $destinationItem.PSIsContainer) {
        throw "The personal skill root is not a directory: $destinationPath"
    }

    [IO.Directory]::CreateDirectory($destinationPath) | Out-Null
    $manifestPath = Join-Path $destinationPath '.agent-toolkit.manifest.json'
    $previousManifest = Get-ToolkitManifest -Path $manifestPath
    if ($null -ne $previousManifest) {
        Remove-ToolkitSkillEntries `
            -DestinationPath $destinationPath `
            -SkillSourcePath $sourcePath `
            -Manifest $previousManifest
    }

    $skills = Get-ChildItem -LiteralPath $sourcePath -Directory | Sort-Object Name
    foreach ($skill in $skills) {
        if (-not [IO.File]::Exists((Join-Path $skill.FullName 'SKILL.md'))) {
            throw "Skill is missing its SKILL.md file: $($skill.FullName)"
        }

        $skillDestination = Join-Path $destinationPath $skill.Name
        $existingItem = Get-Item -LiteralPath $skillDestination -Force -ErrorAction SilentlyContinue
        if ($null -ne $existingItem -and -not $Force) {
            throw "Refusing to replace an unmanaged skill: $skillDestination. Use -Force to replace this name explicitly."
        }
        if ($null -ne $existingItem) {
            Remove-ToolkitPath -Path $skillDestination -ExpectedParentPath $destinationPath
        }

        if ($InstallMode -eq 'Link') {
            $linkType = if ($env:OS -eq 'Windows_NT') { 'Junction' } else { 'SymbolicLink' }
            New-Item -ItemType $linkType -Path $skillDestination -Target $skill.FullName | Out-Null
        }
        else {
            [IO.Directory]::CreateDirectory($skillDestination) | Out-Null
            Get-ChildItem -LiteralPath $skill.FullName -Force |
                Copy-Item -Destination $skillDestination -Recurse -Force
        }
    }

    $manifest = [ordered]@{
        generatedBy = 'coding-agent-toolkit'
        mode = $InstallMode
        sourcePath = $sourcePath
        skills = @($skills.Name)
    } | ConvertTo-Json

    Write-ToolkitGeneratedFile -Path $manifestPath -Content $manifest -Force
}

function Write-ToolkitGeneratedFile {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$Path,

        [Parameter(Mandatory)]
        [string]$Content,

        [switch]$Force
    )

    $fullPath = [IO.Path]::GetFullPath($Path)
    if ([IO.File]::Exists($fullPath) -and -not $Force) {
        if (-not (Test-ToolkitGeneratedFile -Path $fullPath)) {
            throw "Refusing to overwrite a file not generated by coding-agent-toolkit: $fullPath. Use -Force to replace it explicitly."
        }
    }

    $parentPath = [IO.Path]::GetDirectoryName($fullPath)
    [IO.Directory]::CreateDirectory($parentPath) | Out-Null
    [IO.File]::WriteAllText(
        $fullPath,
        $Content.TrimEnd() + [Environment]::NewLine,
        [Text.UTF8Encoding]::new($false)
    )
}

function Get-ToolkitManifest {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$Path
    )

    $fullPath = [IO.Path]::GetFullPath($Path)
    if (-not [IO.File]::Exists($fullPath)) {
        return $null
    }

    try {
        $manifest = [IO.File]::ReadAllText($fullPath) | ConvertFrom-Json
    }
    catch {
        throw "The toolkit manifest is invalid: $fullPath"
    }

    if ($manifest.generatedBy -ne 'coding-agent-toolkit') {
        throw "The manifest is not owned by coding-agent-toolkit: $fullPath"
    }

    return $manifest
}

function Remove-ToolkitPath {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$Path,

        [Parameter(Mandatory)]
        [string]$ExpectedParentPath
    )

    $fullPath = [IO.Path]::GetFullPath($Path)
    $parentPath = [IO.Path]::GetFullPath($ExpectedParentPath).TrimEnd(
        [IO.Path]::DirectorySeparatorChar,
        [IO.Path]::AltDirectorySeparatorChar
    )
    $requiredPrefix = $parentPath + [IO.Path]::DirectorySeparatorChar
    if (-not $fullPath.StartsWith($requiredPrefix, [StringComparison]::OrdinalIgnoreCase)) {
        throw "Refusing to remove a path outside its expected parent: $fullPath"
    }

    $item = Get-Item -LiteralPath $fullPath -Force -ErrorAction SilentlyContinue
    if ($null -eq $item) {
        return
    }

    if (($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
        if ($item.PSIsContainer) {
            [IO.Directory]::Delete($fullPath)
        }
        else {
            [IO.File]::Delete($fullPath)
        }
        return
    }

    if ($item.PSIsContainer) {
        [IO.Directory]::Delete($fullPath, $true)
    }
    else {
        [IO.File]::Delete($fullPath)
    }
}

function Remove-ToolkitSkillEntries {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$DestinationPath,

        [Parameter(Mandatory)]
        [string]$SkillSourcePath,

        [Parameter(Mandatory)]
        [object]$Manifest
    )

    $destinationRoot = [IO.Path]::GetFullPath($DestinationPath)
    $manifestSourceProperty = $Manifest.PSObject.Properties['sourcePath']
    $sourceRoot = if (
        $null -ne $manifestSourceProperty -and
        -not [string]::IsNullOrWhiteSpace($manifestSourceProperty.Value)
    ) {
        [IO.Path]::GetFullPath($manifestSourceProperty.Value)
    }
    else {
        [IO.Path]::GetFullPath($SkillSourcePath)
    }
    $modeProperty = $Manifest.PSObject.Properties['mode']
    $mode = if ($null -ne $modeProperty -and $modeProperty.Value -eq 'Link') { 'Link' } else { 'Copy' }

    foreach ($skillName in @($Manifest.skills)) {
        if ($skillName -notmatch '^[a-zA-Z0-9][a-zA-Z0-9._-]*$') {
            throw "The skill manifest contains an unsafe skill name: $skillName"
        }

        $skillPath = Join-Path $destinationRoot $skillName
        $item = Get-Item -LiteralPath $skillPath -Force -ErrorAction SilentlyContinue
        if ($null -eq $item) {
            continue
        }

        if ($mode -eq 'Link') {
            $expectedTarget = [IO.Path]::GetFullPath((Join-Path $sourceRoot $skillName))
            $pointsToToolkit = @($item.Target) | Where-Object {
                -not [string]::IsNullOrWhiteSpace($_) -and
                [IO.Path]::GetFullPath($_) -eq $expectedTarget
            }
            if (($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -eq 0 -or -not $pointsToToolkit) {
                throw "Refusing to remove a skill path that no longer points to this toolkit: $skillPath"
            }
        }
        elseif (($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
            throw "Refusing to remove a copied skill that was replaced by a filesystem link: $skillPath"
        }

        Remove-ToolkitPath -Path $skillPath -ExpectedParentPath $destinationRoot
    }
}

function Install-ToolkitInstructionFiles {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$InstructionSourcePath,

        [Parameter(Mandatory)]
        [string]$DestinationPath,

        [switch]$Force
    )

    $sourcePath = [IO.Path]::GetFullPath($InstructionSourcePath)
    $destinationRoot = [IO.Path]::GetFullPath($DestinationPath)
    if (-not [IO.Directory]::Exists($sourcePath)) {
        throw "Instruction source directory does not exist: $sourcePath"
    }

    [IO.Directory]::CreateDirectory($destinationRoot) | Out-Null
    $managedPath = Join-Path $destinationRoot 'coding-agent-toolkit'
    $manifestPath = Join-Path $destinationRoot '.coding-agent-toolkit.instructions.json'
    $previousManifest = Get-ToolkitManifest -Path $manifestPath
    $existingItem = Get-Item -LiteralPath $managedPath -Force -ErrorAction SilentlyContinue
    if ($null -ne $existingItem) {
        $pointsToToolkit = @($existingItem.Target) | Where-Object {
            -not [string]::IsNullOrWhiteSpace($_) -and
            [IO.Path]::GetFullPath($_) -eq $sourcePath
        }
        if (($existingItem.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0 -and $pointsToToolkit) {
            return
        }
        $previousSourceProperty = if ($null -ne $previousManifest) {
            $previousManifest.PSObject.Properties['sourcePath']
        }
        else {
            $null
        }
        $pointsToPreviousToolkit = if ($null -ne $previousSourceProperty) {
            @($existingItem.Target) | Where-Object {
                -not [string]::IsNullOrWhiteSpace($_) -and
                [IO.Path]::GetFullPath($_) -eq [IO.Path]::GetFullPath($previousSourceProperty.Value)
            }
        }
        else {
            $null
        }
        if (($existingItem.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0 -and $pointsToPreviousToolkit) {
            Remove-ToolkitPath -Path $managedPath -ExpectedParentPath $destinationRoot
            $existingItem = $null
        }
        if (-not $Force) {
            if ($null -ne $existingItem) {
                throw "Refusing to replace an unmanaged Copilot instruction path: $managedPath. Use -Force to replace this name explicitly."
            }
        }
        if ($null -ne $existingItem) {
            Remove-ToolkitPath -Path $managedPath -ExpectedParentPath $destinationRoot
        }
    }

    $linkType = if ($env:OS -eq 'Windows_NT') { 'Junction' } else { 'SymbolicLink' }
    New-Item -ItemType $linkType -Path $managedPath -Target $sourcePath | Out-Null
    $manifest = [ordered]@{
        generatedBy = 'coding-agent-toolkit'
        sourcePath = $sourcePath
    } | ConvertTo-Json
    Write-ToolkitGeneratedFile -Path $manifestPath -Content $manifest -Force
}

function Remove-ToolkitInstructionFiles {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$InstructionSourcePath,

        [Parameter(Mandatory)]
        [string]$DestinationPath
    )

    $sourcePath = [IO.Path]::GetFullPath($InstructionSourcePath)
    $destinationRoot = [IO.Path]::GetFullPath($DestinationPath)
    $managedPath = Join-Path $destinationRoot 'coding-agent-toolkit'
    $manifestPath = Join-Path $destinationRoot '.coding-agent-toolkit.instructions.json'
    $manifest = Get-ToolkitManifest -Path $manifestPath
    $item = Get-Item -LiteralPath $managedPath -Force -ErrorAction SilentlyContinue
    if ($null -eq $item) {
        if ($null -ne $manifest) {
            [IO.File]::Delete($manifestPath)
        }
        return $false
    }

    $manifestSourceProperty = if ($null -ne $manifest) {
        $manifest.PSObject.Properties['sourcePath']
    }
    else {
        $null
    }
    $expectedSourcePath = if ($null -ne $manifestSourceProperty) {
        [IO.Path]::GetFullPath($manifestSourceProperty.Value)
    }
    else {
        $sourcePath
    }
    $pointsToToolkit = @($item.Target) | Where-Object {
        -not [string]::IsNullOrWhiteSpace($_) -and
        [IO.Path]::GetFullPath($_) -eq $expectedSourcePath
    }
    if (($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -eq 0 -or -not $pointsToToolkit) {
        throw "Refusing to remove a Copilot instruction path not owned by this toolkit: $managedPath"
    }

    Remove-ToolkitPath -Path $managedPath -ExpectedParentPath $destinationRoot
    if ([IO.File]::Exists($manifestPath)) {
        [IO.File]::Delete($manifestPath)
    }
    if (
        [IO.Directory]::Exists($destinationRoot) -and
        [IO.Directory]::GetFileSystemEntries($destinationRoot).Count -eq 0
    ) {
        [IO.Directory]::Delete($destinationRoot)
    }

    return $true
}

