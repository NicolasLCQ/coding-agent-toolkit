Set-StrictMode -Version Latest

$script:GeneratedMarker = '<!-- Generated by coding-agent-toolkit. Do not edit directly. -->'

function Test-ToolkitGeneratedFile {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$Path
    )

    $fullPath = [IO.Path]::GetFullPath($Path)
    if (-not [IO.File]::Exists($fullPath)) {
        return $false
    }

    $existingLines = [IO.File]::ReadAllLines($fullPath)
    return $existingLines.Count -gt 0 -and $existingLines[0] -eq $script:GeneratedMarker
}

function Get-ToolkitInstructionDocument {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$InstructionSourcePath
    )

    $sourcePath = [IO.Path]::GetFullPath($InstructionSourcePath)
    if (-not [IO.Directory]::Exists($sourcePath)) {
        throw "Instruction source directory does not exist: $sourcePath"
    }

    $files = Get-ChildItem -LiteralPath $sourcePath -File -Filter '*.instructions.md' | Sort-Object Name
    if ($files.Count -eq 0) {
        throw "No *.instructions.md files were found in: $sourcePath"
    }

    $sections = foreach ($file in $files) {
        $content = [IO.File]::ReadAllText($file.FullName)
        $body = [Text.RegularExpressions.Regex]::Replace(
            $content,
            '\A---\r?\n.*?\r?\n---\r?\n',
            '',
            [Text.RegularExpressions.RegexOptions]::Singleline
        ).Trim()

        if ([string]::IsNullOrWhiteSpace($body)) {
            throw "Instruction file has no Markdown body: $($file.FullName)"
        }

        "## Source: $($file.Name)`n`n$body"
    }

    return @(
        $script:GeneratedMarker
        '# Shared agent instructions'
        ''
        'These instructions are generated from the files in `instructions/`.'
        'Update those source files and run `./scripts/install.ps1` again.'
        ''
        ($sections -join "`n`n---`n`n")
        ''
    ) -join "`n"
}

function Write-ToolkitGeneratedFile {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$Path,

        [Parameter(Mandatory)]
        [string]$Content,

        [switch]$Force
    )

    $fullPath = [IO.Path]::GetFullPath($Path)
    if ([IO.File]::Exists($fullPath) -and -not $Force) {
        if (-not (Test-ToolkitGeneratedFile -Path $fullPath)) {
            throw "Refusing to overwrite a file not generated by coding-agent-toolkit: $fullPath. Use -Force to replace it explicitly."
        }
    }

    $parentPath = [IO.Path]::GetDirectoryName($fullPath)
    [IO.Directory]::CreateDirectory($parentPath) | Out-Null
    [IO.File]::WriteAllText(
        $fullPath,
        $Content.TrimEnd() + [Environment]::NewLine,
        [Text.UTF8Encoding]::new($false)
    )
}

function Remove-ToolkitManagedDirectory {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$Path,

        [Parameter(Mandatory)]
        [string]$ExpectedParentPath
    )

    $fullPath = [IO.Path]::GetFullPath($Path)
    $parentPath = [IO.Path]::GetFullPath($ExpectedParentPath).TrimEnd(
        [IO.Path]::DirectorySeparatorChar,
        [IO.Path]::AltDirectorySeparatorChar
    )
    $requiredPrefix = $parentPath + [IO.Path]::DirectorySeparatorChar
    if (-not $fullPath.StartsWith($requiredPrefix, [StringComparison]::OrdinalIgnoreCase)) {
        throw "Refusing to remove a managed directory outside its expected parent: $fullPath"
    }

    if (-not [IO.Directory]::Exists($fullPath)) {
        return
    }

    $directory = Get-Item -LiteralPath $fullPath -Force
    if (($directory.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
        throw "Refusing to remove a managed directory that is a filesystem link: $fullPath"
    }

    [IO.Directory]::Delete($fullPath, $true)
}

function Copy-ToolkitSkills {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$SkillSourcePath,

        [Parameter(Mandatory)]
        [string]$DestinationPath,

        [switch]$Force
    )

    $sourcePath = [IO.Path]::GetFullPath($SkillSourcePath)
    $destinationRoot = [IO.Path]::GetFullPath($DestinationPath)
    if (-not [IO.Directory]::Exists($sourcePath)) {
        throw "Skill source directory does not exist: $sourcePath"
    }

    [IO.Directory]::CreateDirectory($destinationRoot) | Out-Null
    $skills = Get-ChildItem -LiteralPath $sourcePath -Directory | Sort-Object Name
    $manifestPath = Join-Path $destinationRoot '.agent-toolkit.manifest.json'
    $managedSkillNames = @()
    if ([IO.File]::Exists($manifestPath)) {
        try {
            $manifestContent = [IO.File]::ReadAllText($manifestPath) | ConvertFrom-Json
            if ($manifestContent.generatedBy -eq 'coding-agent-toolkit') {
                $managedSkillNames = @($manifestContent.skills)
            }
        }
        catch {
            throw "The existing skill manifest is invalid: $manifestPath"
        }
    }

    foreach ($managedSkillName in $managedSkillNames) {
        if ($managedSkillName -notmatch '^[a-zA-Z0-9][a-zA-Z0-9._-]*$') {
            throw "The skill manifest contains an unsafe skill name: $managedSkillName"
        }

        Remove-ToolkitManagedDirectory `
            -Path (Join-Path $destinationRoot $managedSkillName) `
            -ExpectedParentPath $destinationRoot
    }

    foreach ($skill in $skills) {
        if (-not [IO.File]::Exists((Join-Path $skill.FullName 'SKILL.md'))) {
            throw "Skill is missing its SKILL.md file: $($skill.FullName)"
        }

        $skillDestination = Join-Path $destinationRoot $skill.Name
        if (
            [IO.Directory]::Exists($skillDestination) -and
            -not $Force
        ) {
            throw "Refusing to overwrite an unmanaged skill directory: $skillDestination. Use -Force to replace overlapping files explicitly."
        }

        if ([IO.Directory]::Exists($skillDestination)) {
            Remove-ToolkitManagedDirectory `
                -Path $skillDestination `
                -ExpectedParentPath $destinationRoot
        }

        [IO.Directory]::CreateDirectory($skillDestination) | Out-Null
        Get-ChildItem -LiteralPath $skill.FullName -Force |
            Copy-Item -Destination $skillDestination -Recurse -Force
    }

    $manifest = [ordered]@{
        generatedBy = 'coding-agent-toolkit'
        skills = @($skills.Name)
    } | ConvertTo-Json

    Write-ToolkitGeneratedFile `
        -Path (Join-Path $destinationRoot '.agent-toolkit.manifest.json') `
        -Content $manifest `
        -Force
}

